#!/usr/bin/env python3
"""Generate direct and coarse power-of-ten tables for Cox's unrounded scaling.

See <https://research.swtch.com/fp#fast> for an explanation of table entries.

As an extension of Cox's published method, we reconstruct powers of ten required
to support extended precision binary floating-point types using a coarse-fine
method similar to that described in SwiftDtoa (see standard library).
"""

import argparse
from pathlib import Path

MIN_POWER = -4999
MAX_POWER = 4999
STRIDE = 56
DIRECT_MIN_POWER = -357
DIRECT_MAX_POWER = 357
MASK128 = (1 << 128) - 1


def ceil_ratio(numerator, denominator):
    return (numerator + denominator - 1) // denominator


def scaled_power(p, bit_count):
    """ceil(10**p * 2**(bit_count-1-floor(log2(10**p))))."""
    if p >= 0:
        n = 10**p
        lp = n.bit_length() - 1
        shift = bit_count - 1 - lp
        return (n << shift if shift >= 0 else ceil_ratio(n, 1 << -shift)), shift
    d = 10**-p
    lp = -d.bit_length()
    shift = bit_count - 1 - lp
    return ceil_ratio(1 << shift, d), shift


def subtractive(c, limb_count):
    high_shift = 128 * (limb_count - 1)
    high = ceil_ratio(c, 1 << high_shift)
    correction = (high << high_shift) - c
    limbs = [high]
    for i in reversed(range(limb_count - 1)):
        shift = 128 * i
        limb = (correction >> shift) & MASK128
        limbs.append(limb)
    return limbs


def swift_array(name, limb_count, rows):
    element = "(" + ", ".join(["UInt128"] * limb_count) + ")"
    lines = [
        "@available(anyAppleOS 26.0, *)",
        "@usableFromInline",
        f"internal let {name}: [{len(rows)} of {element}] = [",
    ]
    for p, shift, limbs in rows:
        values = ", ".join(f"0x{limb:032x}" for limb in limbs)
        lines.append("  (" + values + f"), // 10**{p} * 2**{shift}")
    return "\n".join(lines + ["]", ""])


HEADER = """// Generated by scripts/generate_powers.py. Do not edit by hand.
//
// The 'direct' table
// ==================
//
// 256-bit mantissas of powers of 10, rounded up, scaled so the highest bit is
// always set, with the high 128-bit limb rounded up followed by the low 128-bit
// limb negated; i.e., an entry `x` represents the value `(x.0 << 128) - x.1`.
//
// The 'coarse' table
// ==================
//
// 384-bit mantissas of selected powers of 10 outside the range of the 'direct'
// table, rounded up, scaled so the highest bit is always set. The high 128-bit
// limbs of entries in the 'direct' table for exponents `0...55` supply exact
// fine multipliers for coarse-fine reconstruction. Entries in this table also
// use a 'subtractive' representation; i.e., an entry `y` represents the value
// `(y.0 << 256) - (y.1 << 128) - y.2`.
"""


def table_entries():
    direct = {}
    for p in range(DIRECT_MIN_POWER, DIRECT_MAX_POWER + 1):
        value, shift = scaled_power(p, 256)
        limbs = subtractive(value, 2)
        direct[p] = limbs, shift
    left_rows = ceil_ratio(DIRECT_MIN_POWER - MIN_POWER, STRIDE)
    left_base = DIRECT_MIN_POWER - left_rows * STRIDE
    right_base = DIRECT_MAX_POWER + 1
    anchors = list(range(left_base, DIRECT_MIN_POWER, STRIDE)) + list(
        range(right_base, MAX_POWER + 1, STRIDE)
    )
    coarse = {}
    for a in anchors:
        value, shift = scaled_power(a, 384)
        limbs = subtractive(value, 3)
        coarse[a] = limbs, shift
    return direct, coarse


def generate_source():
    direct, coarse = table_entries()
    direct_rows = [(p, shift, limbs) for p, (limbs, shift) in direct.items()]
    coarse_rows = [(a, shift, limbs) for a, (limbs, shift) in coarse.items()]
    return "\n".join(
        [
            HEADER,
            swift_array("_cox_direct_pow10", 2, direct_rows),
            swift_array("_cox_coarse_pow10", 3, coarse_rows),
        ]
    )


def main():
    argparse.ArgumentParser(description=__doc__).parse_args()
    target = (
        Path(__file__).resolve().parent.parent
        / "Sources"
        / "DecimalCore"
        / "ConversionPowers.swift"
    )
    target.write_text(generate_source())
    print(f"Generated {target}.")


if __name__ == "__main__":
    main()
